namespace Viv.Contracts.Interface
{
    /// <summary>
    /// 事务提交观察者。
    ///
    /// 与 <see cref="ITransactionAttemptListener"/> 是一对：那个管「这次尝试失败了要撤掉什么」
    /// （按尝试累积的外部状态），这个管「确定成了，把在等它的那些事叫醒」。
    ///
    /// 典型用途是「写库之后马上有人要做后续动作」的场景 —— 发件箱投递器就是靠它在事务提交后
    /// 立刻被唤起，而不是干等下一个轮询间隔。注意观察者只知道「提交了」，不知道提交了什么：
    /// 需要区分内容的，自己按作用域累积状态。
    ///
    /// 事务层刻意不认识具体观察者 —— 它只知道"有人要在提交后知道一声"。
    /// </summary>
    public interface ITransactionObserver
    {
        /// <summary>
        /// 事务真正提交成功后回调一次。
        ///
        /// 只在提交成功时调用：回滚、<c>commitWhen</c> 判负、异常退出都不回调。
        /// 开启重试后一个事务可能被重放多次，重放的失败尝试同样不回调，只有最终提交那次会。
        ///
        /// 实现不应抛异常，也不应做耗时动作 —— 此刻提交已成事实，抛出去只会让调用方
        /// 误以为提交失败（实现方抛出的异常由事务层吞掉并记日志）。
        /// </summary>
        void OnCommitted();
    }
}
